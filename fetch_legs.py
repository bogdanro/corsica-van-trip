def legs(pts):
    u=("https://router.project-osrm.org/route/v1/driving/"
       +";".join(f"{lo},{la}" for la,lo in pts)+"?overview=false")
    j=json.loads(urllib.request.urlopen(urllib.request.Request(u,headers={"User-Agent":"c/1.0"}),timeout=60).read())
    time.sleep(1.1)
    return [{"km":round(l["distance"]/1000,1),"min":round(l["duration"]/60)} for l in j["routes"][0]["legs"]]

